String tr(String key) {
  final rw = AppSettings.instance.language == 'rw';
  return (rw ? (_rw[key] ?? moreRw[key]) : (_en[key] ?? moreEn[key])) ??
      _en[key] ??
      moreEn[key] ??
      key;
}

String trn(String key, Object n) => tr(key).replaceAll('{n}', '$n');

String trp(String key, List<Object> values) {
  var s = tr(key);
  for (var i = 0; i < values.length; i++) {
    s = s.replaceAll('{$i}', '${values[i]}');
  }
  return s;
}

