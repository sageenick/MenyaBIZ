import '../services/settings_service.dart';

/// Text for [key] in the current language (business terms only).
String tr(String key) {
  final rw = AppSettings.instance.language == 'rw';
  return (rw ? _rw : _en)[key] ?? _en[key] ?? key;
}

/// Same as tr, but replaces {n} with a value.
String trn(String key, Object n) => tr(key).replaceAll('{n}', '$n');

